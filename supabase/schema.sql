create table if not exists public.courts (
  id int generated by default as identity primary key,
  name text not null,
  sport text not null default 'futevolei',   -- futevolei | volei | beachtennis
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.reservations (
  id uuid primary key default gen_random_uuid(),
  court_id int not null references public.courts(id),
  sport text not null,
  date date not null,
  start_time time not null,
  duration_hours numeric(3, 1) not null default 1,
  num_players int not null default 2,
  player_name text not null,
  player_phone text not null,
  player_email text not null default '',
  total_price numeric(10, 2) not null default 0,
  payment_method text not null default 'pix',
  status text not null default 'confirmed',   -- confirmed | cancelled
  created_at timestamptz not null default now()
);

create index if not exists reservations_date_idx on public.reservations (date, court_id);

create table if not exists public.trial_classes (
  id uuid primary key default gen_random_uuid(),
  sport text not null,
  level text not null,
  preferred_day text,
  preferred_time text,
  name text not null,
  phone text not null,
  email text not null default '',
  status text not null default 'pending',     -- pending | contacted | scheduled | converted | lost
  created_at timestamptz not null default now()
);

create table if not exists public.court_blocks (
  id uuid primary key default gen_random_uuid(),
  court_id int references public.courts(id) on delete cascade,  -- null = todas as quadras
  date date not null,
  start_time time not null,
  end_time time not null,
  reason text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.events (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  type text not null default 'evento',
  date date not null,
  description text,
  image_url text,
  created_at timestamptz not null default now()
);

